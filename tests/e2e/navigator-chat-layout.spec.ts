import {test,expect} from '@playwright/test';

test('领航员提示可折叠，阶段栏和输入区气泡适配手机与PC',async({page,request})=>{
 const session=await(await request.post('/api/mock-session',{data:{userId:'U-018'}})).json();
 await page.addInitScript(token=>localStorage.setItem('sb-token',token),session.token);
 let assessed=false;
 await page.route('**/api/navigator/state?*',async route=>{const response=await route.fetch();const state=await response.json();await route.fulfill({json:{...state,assessed,stages:{M:'M2',P:'P2',T:'T1'},assessment:null}});});
 await page.setViewportSize({width:390,height:844});
 await page.goto('/advisor/opportunity/OP-UK-026');
 await page.getByRole('button',{name:'新建对话',exact:true}).click();
 const bar=page.locator('.mobile-navigator-entry'),bubbles=page.locator('.navigator-composer-bubbles');
 await expect(bar.getByRole('button',{name:'开始评估',exact:true})).toBeEnabled();
 await bar.getByRole('button',{name:'折叠MPT评估提示'}).click();
 await expect(bar.getByRole('button',{name:'开始评估',exact:true})).toBeHidden();
 await bar.getByRole('button',{name:'展开MPT评估提示'}).click();
 await expect(bar.getByRole('button',{name:'开始评估',exact:true})).toBeVisible();
 await expect(bar.getByRole('button',{name:'项目画像详情',exact:true})).toHaveCount(0);
 await expect(page.locator('.composer').getByRole('button',{name:'准备会晤资料'})).toHaveCount(0);
 await expect(page.locator('.composer .common-tools')).toHaveCount(0);
 const box=await page.locator('.composer').boundingBox(),actions=await bubbles.boundingBox();
 expect(box!.height).toBeLessThan(105);expect(box!.width).toBeLessThan(350);expect(actions!.y+actions!.height).toBeLessThanOrEqual(box!.y);
 await bubbles.getByRole('button',{name:'项目画像详情',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'项目画像详情',exact:true})).toBeVisible();
 await page.getByLabel('关闭画像详情').click();
 await bubbles.getByRole('button',{name:'MPT画布',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'项目画像矩阵',exact:true})).toBeVisible();
 await page.getByLabel('关闭赢单领航员弹窗').click();
 assessed=true;await page.reload();
 const stages=bar.getByLabel('当前项目阶段');await expect(stages).toContainText('S3');
 for(const stage of ['M2','P2','T1'])await expect(stages).toContainText(stage);
 await expect(bar.getByRole('button',{name:'开始评估',exact:true})).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'runtime/reports/screenshots/navigator-chat-mobile.png'});
 await page.setViewportSize({width:1440,height:1000});
 await expect(stages).toBeVisible();await bubbles.getByRole('button',{name:'项目画像详情',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'项目画像详情',exact:true})).toBeVisible();
 await page.getByLabel('关闭画像详情').click();
 await page.screenshot({path:'runtime/reports/screenshots/navigator-chat-desktop.png'});
});
